FString ULabBlueprintCaptureLibrary::CaptureBlueprintGraph(const FString& AssetPath, const FString& GraphName,
    const FString& OutputPng, int32 Width, int32 Height, bool bIncludeTiles)
{
    using namespace LabGraphCapture;
    FObject Report = MakeShared<FJsonObject>();
    TArray<TSharedPtr<FJsonValue>> Errors;
    TArray<TSharedPtr<FJsonValue>> Frames;
    auto Finish = [&]()
    {
        Report->SetBoolField(TEXT("ok"), Errors.IsEmpty());
        Report->SetArrayField(TEXT("errors"), Errors);
        Report->SetArrayField(TEXT("frames"), Frames);
        return Encode(Report);
    };
    auto Error = [&](const FString& Message) { Errors.Add(MakeShared<FJsonValueString>(Message)); };
    Report->SetStringField(TEXT("asset"), AssetPath);
    Report->SetStringField(TEXT("graph"), GraphName);
    Report->SetStringField(TEXT("method"), TEXT("Native SGraphEditor + FWidgetRenderer on a transient Blueprint duplicate; no desktop capture"));
    if (!IsInGameThread() || !FSlateApplication::IsInitialized() || !FApp::CanEverRender())
    {
        Error(TEXT("Requires the editor game thread with Slate and rendering available"));
        return Finish();
    }
    if (Width < 800 || Height < 600 || Width > 4096 || Height > 4096)
    {
        Error(TEXT("Width must be 800..4096 and Height 600..4096"));
        return Finish();
    }
    FString Output = FPaths::ConvertRelativePathToFull(OutputPng);
    FPaths::NormalizeFilename(Output);
    FPaths::CollapseRelativeDirectories(Output);
    const FString Saved = FPaths::ConvertRelativePathToFull(FPaths::ProjectSavedDir());
    if (!FPaths::IsUnderDirectory(Output, Saved) || !FPaths::GetExtension(Output).Equals(TEXT("png"), ESearchCase::IgnoreCase))
    {
        Error(TEXT("Output must be a .png below this project's Saved directory"));
        return Finish();
    }
    UBlueprint* Source = LoadObject<UBlueprint>(nullptr, *AssetPath);
    UEdGraph* SourceGraph = Source ? FindGraph(Source, GraphName) : nullptr;
    if (!Source || !SourceGraph || SourceGraph->Nodes.IsEmpty())
    {
        Error(TEXT("Blueprint or nonempty named graph not found"));
        return Finish();
    }
    const FString Before = GraphState(SourceGraph);
    const bool bDirtyBefore = Source->GetOutermost()->IsDirty();
    Report->SetBoolField(TEXT("source_package_dirty_before"), bDirtyBefore);
    Report->SetStringField(TEXT("source_graph_hash_before"), FMD5::HashAnsiString(*Before));
    Report->SetNumberField(TEXT("source_node_count"), SourceGraph->Nodes.Num());

    // Native comment/node widgets may cache sizes during layout. Keep even that
    // presentation bookkeeping away from the actual asset and its open editor.
    TStrongObjectPtr<UBlueprint> RenderCopy(DuplicateObject<UBlueprint>(Source, GetTransientPackage(),
        MakeUniqueObjectName(GetTransientPackage(), UBlueprint::StaticClass(), TEXT("LabGraphCapture"))));
    if (!RenderCopy.IsValid())
    {
        Error(TEXT("Could not create a transient render copy"));
        return Finish();
    }
    RenderCopy->ClearFlags(RF_Public | RF_Standalone);
    RenderCopy->SetFlags(RF_Transient);
    UEdGraph* RenderGraph = FindGraph(RenderCopy.Get(), GraphName);
    if (!RenderGraph)
    {
        Error(TEXT("Named graph missing from transient copy"));
        return Finish();
    }

    TSharedRef<SGraphEditor> Widget = SNew(SGraphEditor)
        .GraphToEdit(RenderGraph)
        .IsEditable(false)
        .DisplayAsReadOnly(false)
        .ShowGraphStateOverlay(false);
    SGraphPanel* Panel = Widget->GetGraphPanel();
    if (!Panel)
    {
        Error(TEXT("Native graph panel could not be constructed"));
        return Finish();
    }
    Panel->Update(); // Public native API: populate widgets without a desktop window/timer.
    Widget->SetViewLocation(FVector2f::ZeroVector, 1.f);
    Widget->SlatePrepass(1.f);
    const FVector2D DrawSize(Width, Height);
    FWidgetRenderer Renderer(true, true);
    TStrongObjectPtr<UTextureRenderTarget2D> Target(FWidgetRenderer::CreateTargetFor(DrawSize, TF_Bilinear, true));
    if (!Target.IsValid())
    {
        Error(TEXT("Could not allocate the render target"));
        return Finish();
    }
    for (int32 Pass = 0; Pass < 2; ++Pass)
    {
        Renderer.DrawWidget(Target.Get(), Widget, DrawSize, 1.f/60.f, false);
        FlushRenderingCommands();
    }

    FSlateRect Bounds(FLT_MAX, FLT_MAX, -FLT_MAX, -FLT_MAX);
    int32 Measured = 0;
    for (UEdGraphNode* Node : RenderGraph->Nodes)
    {
        FSlateRect NodeBounds;
        if (Node && Widget->GetBoundsForNode(Node, NodeBounds, 0.f))
        {
            Bounds.Left = FMath::Min(Bounds.Left, NodeBounds.Left);
            Bounds.Top = FMath::Min(Bounds.Top, NodeBounds.Top);
            Bounds.Right = FMath::Max(Bounds.Right, NodeBounds.Right);
            Bounds.Bottom = FMath::Max(Bounds.Bottom, NodeBounds.Bottom);
            ++Measured;
        }
    }
    Report->SetNumberField(TEXT("native_measured_node_count"), Measured);
    if (Measured != RenderGraph->Nodes.Num() || Bounds.Right <= Bounds.Left || Bounds.Bottom <= Bounds.Top)
    {
        Error(TEXT("Native node widget layout incomplete; no schematic fallback was generated"));
        return Finish();
    }
    Bounds.Left -= 96.f; Bounds.Top -= 96.f;
    Bounds.Right += 96.f; Bounds.Bottom += 96.f;
    Report->SetArrayField(TEXT("graph_bounds"), Numbers({Bounds.Left, Bounds.Top, Bounds.Right, Bounds.Bottom}));
    const float GraphWidth = Bounds.Right - Bounds.Left;
    const float GraphHeight = Bounds.Bottom - Bounds.Top;
    if (!IFileManager::Get().MakeDirectory(*FPaths::GetPath(Output), true))
    {
        Error(TEXT("Could not create the output directory"));
        return Finish();
    }

    auto RenderFrame = [&](const FString& Filename, const FVector2f& View, float Zoom, const FString& Kind)
    {
        Widget->SetViewLocation(View, Zoom);
        Widget->SlatePrepass(1.f);
        for (int32 Pass = 0; Pass < 2; ++Pass)
        {
            Renderer.DrawWidget(Target.Get(), Widget, DrawSize, 1.f/60.f, false);
            FlushRenderingCommands();
        }
        TArray<FColor> Pixels;
        FReadSurfaceDataFlags Flags(RCM_UNorm);
        Flags.SetLinearToGamma(false); // Render target already uses Slate gamma-space output.
        if (!Target->GameThread_GetRenderTargetResource()->ReadPixels(Pixels, Flags) || Pixels.Num() != Width*Height)
        {
            Error(TEXT("Render target readback failed: ") + Filename);
            return false;
        }
        for (FColor& Pixel : Pixels) Pixel.A = 255;
        TArray64<uint8> Compressed;
        FImageUtils::PNGCompressImageArray(Width, Height, TArrayView64<const FColor>(Pixels.GetData(), Pixels.Num()), Compressed);
        if (Compressed.IsEmpty() || !FFileHelper::SaveArrayToFile(Compressed, *Filename))
        {
            Error(TEXT("PNG write failed: ") + Filename);
            return false;
        }
        FVector2f ActualView;
        float ActualZoom = 1.f;
        Widget->GetViewLocation(ActualView, ActualZoom);
        FObject Frame = MakeShared<FJsonObject>();
        Frame->SetStringField(TEXT("path"), Filename);
        Frame->SetStringField(TEXT("kind"), Kind);
        Frame->SetNumberField(TEXT("zoom"), ActualZoom);
        Frame->SetArrayField(TEXT("view_origin"), Numbers({ActualView.X,ActualView.Y}));
        Frame->SetArrayField(TEXT("pixels"), Numbers({static_cast<double>(Width),static_cast<double>(Height)}));
        Frames.Add(MakeShared<FJsonValueObject>(Frame));
        return true;
    };

    const float Fit = FMath::Min(1.f, FMath::Min(Width/GraphWidth, Height/GraphHeight));
    float RequestedZoom = Fit;
    float ActualZoom = 1.f;
    FVector2f ActualView;
    for (int32 Attempt = 0; Attempt < 10; ++Attempt)
    {
        Widget->SetViewLocation(FVector2f(Bounds.Left,Bounds.Top), RequestedZoom);
        Widget->GetViewLocation(ActualView, ActualZoom);
        if (ActualZoom <= Fit + 0.001f) break;
        RequestedZoom *= 0.85f; // Native graph zoom levels are discrete.
    }
    const bool bOverviewFits = ActualZoom <= Fit + 0.001f;
    Report->SetBoolField(TEXT("overview_fits"), bOverviewFits);
    const FVector2f OverviewView(Bounds.Left-(Width/ActualZoom-GraphWidth)*0.5f,
        Bounds.Top-(Height/ActualZoom-GraphHeight)*0.5f);
    RenderFrame(Output, OverviewView, ActualZoom, TEXT("overview_native_zoom"));

    if (bIncludeTiles)
    {
        constexpr float Overlap = 160.f;
        const int32 Columns = FMath::Max(1, FMath::CeilToInt((GraphWidth-Overlap)/(Width-Overlap)));
        const int32 Rows = FMath::Max(1, FMath::CeilToInt((GraphHeight-Overlap)/(Height-Overlap)));
        Report->SetArrayField(TEXT("tile_grid"), Numbers({static_cast<double>(Columns),static_cast<double>(Rows)}));
        if (Columns*Rows > 64)
        {
            Error(TEXT("Graph requires more than 64 tiles; increase Width/Height or capture a smaller named graph"));
        }
        else
        {
            const FString Stem = FPaths::Combine(FPaths::GetPath(Output), FPaths::GetBaseFilename(Output));
            for (int32 Row = 0; Row < Rows && Errors.IsEmpty(); ++Row)
            {
                for (int32 Column = 0; Column < Columns && Errors.IsEmpty(); ++Column)
                {
                    const float X = Bounds.Left + FMath::Min(Column*(Width-Overlap), FMath::Max(0.f,GraphWidth-Width));
                    const float Y = Bounds.Top + FMath::Min(Row*(Height-Overlap), FMath::Max(0.f,GraphHeight-Height));
                    const FString Tile = Stem + FString::Printf(TEXT("_tile_%02d_%02d.png"),Row+1,Column+1);
                    RenderFrame(Tile, FVector2f(X,Y), 1.f, TEXT("native_100_percent_tile"));
                }
            }
        }
    }
    FlushRenderingCommands();
    const FString After = GraphState(SourceGraph);
    const bool bUnchanged = Before == After && Source->GetOutermost()->IsDirty() == bDirtyBefore;
    Report->SetBoolField(TEXT("source_unchanged"), bUnchanged);
    Report->SetBoolField(TEXT("source_package_dirty_after"), Source->GetOutermost()->IsDirty());
    Report->SetStringField(TEXT("source_graph_hash_after"), FMD5::HashAnsiString(*After));
    if (!bUnchanged) Error(TEXT("Source state changed unexpectedly during capture; do not treat this as a verified read-only result"));
    const FString Manifest = FPaths::ChangeExtension(Output, TEXT("json"));
    Report->SetStringField(TEXT("manifest"), Manifest);
    const FString Result = Finish();
    if (!FFileHelper::SaveStringToFile(Result, *Manifest, FFileHelper::EEncodingOptions::ForceUTF8WithoutBOM))
    {
        Error(TEXT("Manifest write failed"));
        return Finish();
    }
    return Result;
}
