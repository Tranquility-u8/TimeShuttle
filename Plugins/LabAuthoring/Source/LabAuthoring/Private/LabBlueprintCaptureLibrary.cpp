using FObject = TSharedPtr<FJsonObject>;

FString Encode(const FObject& Object)
{
    FString Text;
    const TSharedRef<TJsonWriter<>> Writer = TJsonWriterFactory<>::Create(&Text);
    FJsonSerializer::Serialize(Object.ToSharedRef(), Writer);
    return Text;
}

// Compare the source, including its drawing positions and all pins/links, after rendering.
FString GraphState(const UEdGraph* Graph)
{
    FString Result;
    for (const UEdGraphNode* Node : Graph->Nodes)
    {
        if (!Node) continue;
        Result += FString::Printf(TEXT("%s|%s|%d|%d|%d|%d|%s\n"),
            *Node->NodeGuid.ToString(), *Node->GetClass()->GetPathName(), Node->NodePosX,
            Node->NodePosY, Node->NodeWidth, Node->NodeHeight, *Node->NodeComment);
        for (const UEdGraphPin* Pin : Node->Pins)
        {
            if (!Pin) continue;
            Result += FString::Printf(TEXT("%s|%s|%d|%s|%s|%s|%s\n"),
                *Pin->PinId.ToString(), *Pin->PinName.ToString(), static_cast<int32>(Pin->Direction),
                *Pin->DefaultValue, *Pin->AutogeneratedDefaultValue,
                *Pin->DefaultTextValue.ToString(), *GetPathNameSafe(Pin->DefaultObject));
            for (const UEdGraphPin* Other : Pin->LinkedTo)
            {
                if (Other) Result += Other->GetOwningNode()->NodeGuid.ToString() + TEXT(":") + Other->PinId.ToString() + TEXT(";");
            }
            Result += TEXT("\n");
        }
    }
    return Result;
}

UEdGraph* FindGraph(UBlueprint* Blueprint, const FString& Name)
{
    TArray<UEdGraph*> Graphs;
    Blueprint->GetAllGraphs(Graphs);
    for (UEdGraph* Graph : Graphs)
    {
        if (Graph && Graph->GetName() == Name) return Graph;
    }
    return nullptr;
}

TArray<TSharedPtr<FJsonValue>> Numbers(std::initializer_list<double> Values)
{
    TArray<TSharedPtr<FJsonValue>> Result;
    for (double Value : Values) Result.Add(MakeShared<FJsonValueNumber>(Value));
    return Result;
}
